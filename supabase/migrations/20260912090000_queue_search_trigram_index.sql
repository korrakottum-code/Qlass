-- ดัชนีสำหรับค้นหาคิวด้วยชื่อ/เบอร์ (ค้นแบบ "มีคำนี้อยู่ตรงไหนก็ได้")
--
-- หน้าตารางคิวค้นด้วย ilike '%คำ%' ซึ่งดัชนี B-tree ปกติใช้ไม่ได้เลย ต้องอ่านทั้งตาราง
-- ทุกครั้ง วัดบนข้อมูลจริง 179,000 แถว: ค้นชื่อ+นามสกุล 337ms และเวลาจะโตตามจำนวนแถว
-- (คิวเพิ่มวันละ ~1,300 แถว ปีหน้าจะแตะหลักวินาที)
--
-- หลังมีดัชนีนี้: ค้นชื่อ+นามสกุล 0.84ms / ไม่เจอเลย 0.33ms และไม่โตตามจำนวนแถวอีก
-- ขนาดดัชนี ~13MB (name) + ~7MB (phone) เทียบกับตาราง 109MB
--
-- หมายเหตุการนำขึ้นโปรดักชัน: ตอนลงจริง 12 ก.ย. 2569 ใช้ CREATE INDEX CONCURRENTLY
-- (หน้าร้านเปิดอยู่ ห้ามล็อกตาราง) ซึ่งรันในทรานแซกชันไม่ได้ จึงยิงตรงทีละคำสั่ง
-- ไฟล์นี้เก็บไว้ให้ฐานข้อมูลที่สร้างใหม่ได้โครงสร้างเดียวกัน — ตอนสร้างใหม่ตารางยังว่าง
-- ล็อกชั่วครู่ไม่มีผล จึงไม่ต้อง CONCURRENTLY
create extension if not exists pg_trgm;

create index if not exists idx_queues_name_trgm
  on public.queues using gin (name gin_trgm_ops);

create index if not exists idx_queues_phone_trgm
  on public.queues using gin (phone gin_trgm_ops);
