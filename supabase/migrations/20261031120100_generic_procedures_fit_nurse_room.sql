-- เหตุผล: หน้าเว็บเวอร์ชันเก่าเทียบ procedure.roomType === room.type ตรง ๆ ถ้าใครโหลดเว็บเก่า
-- หลังจากไฟล์นี้ลงไป สองหัตถการนี้จะหายจากรายการของเตียง M ที่ยังไม่ตั้งล็อก (78 เตียง)
-- และค้างอยู่อย่างนั้นจนกว่าจะรีเฟรช เพราะแอปไม่มีระบบรีโหลดเอง
-- ต้องลงก่อนเปิดใช้ห้อง N เตียงแรก ไม่งั้นห้อง N ลงสองตัวนี้ไม่ได้

set local lock_timeout = '3s';

update public.procedures
   set room_type = 'MN'
 where room_type = 'M'
   and name in ('Influencer', 'ปรึกษาทั่วไป');
