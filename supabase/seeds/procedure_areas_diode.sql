-- เปิดสวิตช์ "บริเวณ" ให้ Diode และ Go-Diode
--
-- ═══ สถานะ: รันไปแล้วบนโปรดักชัน 2026-09-09 เวลา 00:38 และ 00:48 น. ═══
-- ไฟล์นี้เก็บไว้เป็นบันทึกว่าของจริงมีอะไรอยู่ และไว้ตั้งค่าใหม่ถ้าโดนลบทั้งชุด
-- รันซ้ำได้ ไม่สร้างซ้ำ (on conflict do nothing ตาม unique index procedure_id + ชื่อ)
--
-- ไฟล์นี้ไม่ใช่ migration — ตั้งใจแยกออกมา เพราะการลง migration ต้องไม่เปลี่ยนพฤติกรรม
-- อะไรเลย ส่วนไฟล์นี้คือขั้นตอน "เปิดใช้จริง" ที่ทำทีหลัง นอกเวลาทำการ
-- และแจ้งทีมหน้าร้านก่อน
--
-- ═══ เวลาที่ใช้ (เจ้าของยืนยัน) ═══
-- แขน / ขา / ขาล่าง / หลัง = 20 นาที, hollywood = 30, ที่เหลือ = 15
-- [1 บล็อค = 5 นาที]  "ขาล่าง" ยืนยันแยกทีหลัง 2026-09-09 ว่าเท่าขาเต็ม
-- แก้เวลาทีหลังได้ในหน้า "จัดการหัตถการ" ไม่ต้องแก้ไฟล์นี้แล้วรันซ้ำ
--
-- ═══ ชื่อบริเวณมาจากไหน ═══
-- อ้างอิงชื่อโปรที่ใช้จริงในระบบ (Diode 27 โปร / Go-Diode 13 โปร)
-- Go-Diode ใช้ชุดเดียวกับ Diode เพื่อให้พนักงานที่ทำงานสองแบรนด์เห็นปุ่มชุดเดียวกัน
-- แม้โปรฝั่ง Go จะไม่มี "หลัง" กับ "ใบหน้า" ขายอยู่เลย — ถ้าสาขา Go ไม่ได้ทำจริง
-- ลบสองอันนั้นทิ้งได้ในหน้าจัดการหัตถการ
--
-- ═══ ปิดกลับ ═══
-- ในแอป: จัดการหัตถการ → กดคอลัมน์ "บริเวณ" ของหัตถการนั้น → "ปิดบริเวณทั้งหมด"
-- หรือ SQL:
--   delete from public.procedure_areas
--   where procedure_id in (select id from public.procedures where name in ('Diode', 'Go-Diode'));
-- ⚠️ ตารางนี้ไม่ได้เปิด Realtime (เจ้าของตัดสินใจ 2026-09-09 ว่าไม่ต้อง) — เครื่องที่เปิด
--    แอปค้างไว้จะยังใช้บริเวณต่อจนกว่าจะรีเฟรช ถ้าปิดฉุกเฉินกลางวันต้องบอกทีมให้รีเฟรชด้วย

begin;

insert into public.procedure_areas (procedure_id, name, blocks, sort_order)
select p.id, v.name, v.blocks, v.sort_order
from public.procedures p
cross join (values
  ('รักแร้',      3, 10),
  ('หนวด',       3, 20),
  ('เครา',       3, 30),
  ('ใบหน้า',      3, 40),
  ('แขน',        4, 50),
  ('ขา',         4, 60),
  ('ขาล่าง',      4, 70),
  ('หลัง',        4, 80),
  ('Hollywood',  6, 90)
) as v(name, blocks, sort_order)
where p.name in ('Diode', 'Go-Diode')
on conflict do nothing;

commit;

