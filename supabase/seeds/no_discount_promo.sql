-- เปิดสวิตช์ "บังคับเลือกโปร" — เพิ่มโปรสำรอง "ไม่มีส่วนลด" ใช้ได้ทุกหัตถการ
--
-- ═══ ทำไมต้องมีไฟล์นี้ ═══
-- เจ้าของงานพบว่า ~500 คิว/เดือนพิมพ์ประเภทลูกค้าเป็น "ใช้คอร์ส" แต่ลืมติ๊กโปร
-- "ใช้คอร์ส" ตกไปกอง "ไม่ระบุโปร" ในหน้าสรุปเงียบ ๆ — ตัดสินใจบังคับให้ต้องเลือกโปร
-- ก่อนบันทึกคิวใหม่เสมอ (ดู App.jsx handleBookingSubmit + onSubmitBooking ของ Timeline)
--
-- ปัญหาคือ ณ วันที่เขียนไฟล์นี้ ไม่มีโปรตัวไหนใช้ได้กับทุกหัตถการเลย (procedure_id
-- ทุกแถวไม่เป็น null สักแถวเดียว) ถ้าบังคับเลือกโดยไม่มีตัวเลือกสำหรับ "จ่ายเต็มราคา
-- ไม่มีส่วนลด" ลูกค้ากลุ่มนี้ (เดือนนี้มีจริง: ลูกค้าใหม่ 92 + ลูกค้าเก่า 128 คิว) จะ
-- บันทึกคิวไม่ได้เลย — ไฟล์นี้เติมช่องว่างนั้นก่อนโค้ดที่บังคับเลือกจะขึ้นจริง
--
-- ═══ ทำไมเป็นไฟล์ seed แยก ไม่ใช่ migration ═══
-- แพทเทิร์นเดียวกับ procedure_areas_diode.sql — การเพิ่มข้อมูลที่เปลี่ยนพฤติกรรมที่
-- พนักงานเห็นทันที (มีตัวเลือกใหม่โผล่ในดรอปดาวน์ทุกหัตถการ) ต้องแยกจาก migration
-- (โครงสร้างล้วน ไม่เปลี่ยนพฤติกรรม) และรันตอนที่ตัดสินใจเปิดใช้จริงเท่านั้น
--
-- ═══ ลำดับสำคัญมาก ═══
-- ต้องรันไฟล์นี้ก่อน merge/deploy โค้ดที่บังคับเลือกโปร ไม่งั้นมีช่วงเวลาที่หัตถการ
-- ที่ไม่มีโปรกำหนดไว้เลย จะบังคับเลือกแต่ไม่มีตัวเลือกให้เลือก = บันทึกคิวไม่ได้
--
-- ═══ จุดเปราะที่ต้องรู้ไว้ ═══
-- ถ้าโปรแถวนี้ถูกลบออกจากหน้า "จัดการโปร" ทีหลัง (ไม่ว่าตั้งใจหรือพลาด) ระบบจะกลับไป
-- ไม่มีทางออกสำหรับลูกค้าที่ไม่มีส่วนลดทันที และคนอื่นจะไม่รู้ว่าทำไมบันทึกคิวไม่ได้
-- ถ้าต้องลบ ต้องปิดโค้ดที่บังคับเลือกก่อน (หรือเพิ่มโปรทดแทนที่ procedure_id เป็น null)
--
-- รันซ้ำได้ ไม่สร้างซ้ำ (เช็คด้วย not exists เพราะตาราง promos ไม่มี unique index
-- ที่ครอบชื่อ+procedure_id ให้ใช้ on conflict ได้)

begin;

insert into public.promos (name, procedure_id, price, active)
select 'ไม่มีส่วนลด', null, 0, true
where not exists (
  select 1 from public.promos where name = 'ไม่มีส่วนลด' and procedure_id is null
);

commit;
