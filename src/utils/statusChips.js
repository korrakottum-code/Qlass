// ชิปสรุปสถานะบนหัวตารางคิว — ตัดสินใจว่าจะโชว์ชิปไหน เรียงยังไง
//
// สองกติกาที่มาจากของจริงหน้างาน:
// 1) เรียงก้อนใหญ่ขึ้นก่อน — แถบชิปเลื่อนแนวนอน บนมือถือเห็นได้ราวสามชิปแรก
//    ถ้าเรียงตามลำดับสถานะ "มาแล้ว/เสร็จ" จะอยู่ท้ายสุดเสมอและตกขอบจอ วันที่ผ่านมาแล้ว
//    จะเหลือให้เห็นแต่ ยืนยันแล้ว/ไม่มาตามนัด/ยกเลิก แล้วอ่านกันว่าวันนั้นมีแต่คนไม่มา
// 2) สถานะที่กำลังกรองอยู่ต้องอยู่ในแถวเสมอแม้นับได้ 0 — ไม่งั้นชิปหายไปทั้งที่ตัวกรอง
//    ยังทำงาน ตารางว่างเปล่าโดยไม่มีอะไรบอกว่ากรองค้างไว้ คนดูจะสรุปว่าข้อมูลหาย
export function buildStatusChips(statuses, counts, activeStatus = "all") {
  const stats = counts || {};
  return (statuses || [])
    .filter((s) => stats[s.value] || s.value === activeStatus)
    .map((s) => ({ ...s, count: stats[s.value] || 0 }))
    .sort((a, b) => b.count - a.count);
}
